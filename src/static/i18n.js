// Keep source text for the persistent shell so language switching is reversible.
(() => {
  const originalText = new WeakMap();
  const originalAttributes = new WeakMap();
  window.ML_TRANSLATE = (root, language) => {
    const translate = (text) => {
      if (language !== "en") return text;
      const trimmed = text.trim();
      if (window.ML_UI_EN[trimmed])
        return text.replace(trimmed, window.ML_UI_EN[trimmed]);
      for (const [ru, en] of [
        ["Просмотреть:", "Preview:"],
        ["Скачать:", "Download:"],
        ["Убрать фильтр по теме", "Remove topic filter"],
      ]) {
        if (trimmed.startsWith(ru)) return text.replace(ru, en);
      }
      return text;
    };
    const walker = document.createTreeWalker(root, NodeFilter.SHOW_TEXT);
    let node;
    while ((node = walker.nextNode())) {
      if (
        node.parentElement.closest(
          ".prose, .notebook-cell, .notebook-markdown, script, style",
        )
      )
        continue;
      if (!originalText.has(node)) originalText.set(node, node.textContent);
      node.textContent = translate(originalText.get(node));
    }
    root
      .querySelectorAll("[aria-label], [placeholder], [title]")
      .forEach((el) => {
        if (el.closest(".prose, .notebook-cell, .notebook-markdown")) return;
        if (!originalAttributes.has(el))
          originalAttributes.set(
            el,
            Object.fromEntries(
              ["aria-label", "placeholder", "title"]
                .filter((a) => el.hasAttribute(a))
                .map((a) => [a, el.getAttribute(a)]),
            ),
          );
        for (const [attribute, value] of Object.entries(
          originalAttributes.get(el),
        ))
          el.setAttribute(attribute, translate(value));
      });
  };
  window.ML_GET_LANGUAGE = () => {
    let saved;
    try {
      saved = localStorage.getItem("ml-course-language");
    } catch {
      /* Storage can be disabled. */
    }
    return ["ru", "en"].includes(saved)
      ? saved
      : navigator.language.toLowerCase().startsWith("ru")
        ? "ru"
        : "en";
  };
  window.ML_SAVE_LANGUAGE = (lang) => {
    try {
      localStorage.setItem("ml-course-language", lang);
    } catch {
      /* The URL still records the selection. */
    }
  };
})();
